using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System;
using System.Collections.Generic;
using System.Text;

namespace Queryeables.Generated;

[Generator]
public sealed class EntityCacheGenerator : IIncrementalGenerator
{
    private const string AttributeName =
        "Queryeables.Abstraction.EntityCacheAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entities = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol)
            .Collect();


        context.RegisterSourceOutput(entities, static (spc, symbols) =>
        {
            var types = symbols
                .GroupBy(t => t.ToDisplayString(
                    SymbolDisplayFormat.FullyQualifiedFormat))
                .Select(g => g.First())
                .OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal)
                .ToArray();

            foreach (var group in types.GroupBy(
                t => t.ContainingNamespace.IsGlobalNamespace
                    ? string.Empty
                    : t.ContainingNamespace.ToDisplayString()))
            {
                var sb = new StringBuilder();

                sb.AppendLine("// <auto-generated />");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
                sb.AppendLine();

                if (!string.IsNullOrEmpty(group.Key))
                {
                    sb.Append("namespace ")
                      .Append(group.Key)
                      .AppendLine(";");
                    sb.AppendLine();
                }

                sb.AppendLine(
                    "public static class EntityCacheServiceCollectionExtensions");
                sb.AppendLine("{");

                var validTypes = group
                    .Select(type => new
                    {
                        Type = type,
                        Key = GetIdProperty(type)
                    })
                    .Where(x => x.Key is not null)
                    .ToArray();

                foreach (var item in validTypes)
                    AppendCacheMethod(sb, item.Type, item.Key!);

                sb.AppendLine();
                sb.AppendLine(
                    "    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddEntityCaches(");
                sb.AppendLine(
                    "        this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
                sb.AppendLine("    {");
                sb.AppendLine(
                    "        global::System.ArgumentNullException.ThrowIfNull(services);");

                foreach (var item in validTypes)
                {
                    sb.Append("        services.Add")
                      .Append(item.Type.Name)
                      .AppendLine("Cache();");
                }

                sb.AppendLine("        return services;");
                sb.AppendLine("    }");
                sb.AppendLine("}");

                var hint = string.IsNullOrEmpty(group.Key)
                    ? "Global"
                    : string.Join("_", group.Key.Split('.'));

                spc.AddSource(
                    $"EntityCacheServiceCollectionExtensions.{hint}.g.cs",
                    sb.ToString());
            }
        });

    }

    private static void AppendCacheMethod(
        StringBuilder sb,
        INamedTypeSymbol entity,
        IPropertySymbol key)
    {
        var entityType = entity.ToDisplayString(
            SymbolDisplayFormat.FullyQualifiedFormat);

        var keyType = key.Type.ToDisplayString(
            SymbolDisplayFormat.FullyQualifiedFormat);

        var propertyName = EscapeIdentifier(key.Name);

        sb.AppendLine();
        sb.Append("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection Add")
          .Append(entity.Name)
          .AppendLine("Cache(");

        sb.AppendLine(
            "        this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("    {");
        sb.AppendLine(
            "        global::System.ArgumentNullException.ThrowIfNull(services);");

        sb.Append("        return services.AddSingleton<")
          .Append("global::Queryeables.Abstraction.IEntityCache<")
          .Append(entityType).Append(", ").Append(keyType)
          .AppendLine(">>(sp =>");

        sb.AppendLine("            new global::Queryeables.Abstraction.EntityCache<");
        sb.Append("                ").Append(entityType).Append(", ")
          .Append(keyType).AppendLine(">(");

        sb.AppendLine(
            "                () => sp.GetRequiredService<global::Queryeables.Abstraction.IEntityStore>(),");

        sb.Append("                entity => entity.")
          .Append(propertyName).AppendLine(",");

        sb.Append("                sp.GetRequiredService<global::Queryeables.Abstraction.IDbMonitor<")
          .Append(entityType).AppendLine(">>(),");

        sb.Append("                global::Queryeables.Abstraction.DbRecordKey.Parse<")
          .Append(keyType).AppendLine(">));");

        sb.AppendLine("    }");
    }

    private static string EscapeIdentifier(string identifier)
    {
        return Microsoft.CodeAnalysis.CSharp.SyntaxFacts
            .GetKeywordKind(identifier) !=
            Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
                ? "@" + identifier
                : identifier;
    }


    private static IPropertySymbol? GetIdProperty(INamedTypeSymbol type)
    {
        return type.GetMembers("Id").AddRange(type.BaseType?.GetMembers("Id") ?? [])
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p =>
                !p.IsStatic &&
                p.Parameters.Length == 0 &&
                p.GetMethod is not null &&
                p.DeclaredAccessibility == Accessibility.Public);
    }

}

