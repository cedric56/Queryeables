using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Queryeables.Generators;

[Generator]
public sealed class EntityGraphGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "Queryeables.Abstraction.EntityGraphAttribute",
                predicate: static (node, _) => node is PropertyDeclarationSyntax,
                transform: static (ctx, _) => GetGraphInfo(ctx))
            .Where(static info => info is not null);

        // On regroupe par classe parente
        var grouped = properties.Collect()
            .Select(static (list, _) => list
                .GroupBy(x => x!.ParentType, SymbolEqualityComparer.Default)
                .ToImmutableArray());

        context.RegisterSourceOutput(grouped, static (spc, groups) =>
        {
            foreach (var group in groups)
            {
                if (group.Key is not INamedTypeSymbol parentType) continue;
                GenerateGraph(parentType, group.ToImmutableArray(), spc);
            }
        });
    }

    private static GraphInfo? GetGraphInfo(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not IPropertySymbol property)
            return null;

        var parentType = property.ContainingType;
        var collectionType = property.Type;

        // On récupère le type de l'enfant (List<Contact> → Contact)
        ITypeSymbol? childType = null;
        if (collectionType is INamedTypeSymbol named && named.IsGenericType)
        {
            childType = named.TypeArguments.FirstOrDefault();
        }

        if (childType is null)
            return null;

        return new GraphInfo(parentType, property, childType);
    }

    private static void GenerateGraph(
        INamedTypeSymbol parentType,
        ImmutableArray<GraphInfo?> relations,
        SourceProductionContext context)
    {
        var parentName = parentType.Name;               // Person
        var graphName = parentName + "Graph";           // PersonGraph
        var keyType = FindKeyType(parentType) ?? "long";

        var ns = parentType.ContainingNamespace.IsGlobalNamespace
            ? null
            : parentType.ContainingNamespace.ToDisplayString();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Queryeables.Abstraction;");
        sb.AppendLine();

        if (ns is not null)
        {
            //sb.AppendLine($"namespace {ns};");
            sb.AppendLine($"namespace Queryeables.Generated;");
            sb.AppendLine();
        }

        // Classe Graph
        sb.AppendLine($"public sealed class {graphName}(IEntityCache<{parentName}, {keyType}> cache) : I{graphName}");
        sb.AppendLine("{");

        // Méthodes Attach pour chaque relation
        foreach (var rel in relations)
        {
            if (rel is null) continue;

            var childName = rel.ChildType.Name;                 // Contact
            var propName = rel.Property.Name;                   // Contacts
            var attachMethod = "Attach" + propName;             // AttachContacts

            sb.AppendLine($"    public void {attachMethod}({parentName} parent, IEnumerable<{childName}> children)");
            sb.AppendLine("    {");
            sb.AppendLine("        foreach (var child in children)");
            sb.AppendLine("        {");
            sb.AppendLine($"            // TODO: logique d'attachement (navigation properties)");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Méthode Create
        sb.AppendLine($"    public static EntityGraph<{parentName}, {keyType}> Create(I{graphName}? graph = null)");
        sb.AppendLine($"        => EntityGraph.For<{parentName}, {keyType}>(p => p.Id)");

        foreach (var rel in relations)
        {
            if (rel is null) continue;

            var propName = rel.Property.Name;
            var childName = rel.ChildType.Name;
            var attachMethod = "Attach" + propName;

            sb.AppendLine($"            .HasMany(p => p.{propName},");
            sb.AppendLine($"                     foreignKey: c => c.Id{parentName},   // ← à adapter");
            sb.AppendLine($"                     key: c => c.Id,");
            sb.AppendLine($"                     onLoaded: graph is null ? null : graph.{attachMethod})");
        }

        sb.AppendLine("            ;");
        sb.AppendLine("}");
        sb.AppendLine();

        // Interface
        sb.AppendLine($"public interface I{graphName}");
        sb.AppendLine("{");
        foreach (var rel in relations)
        {
            if (rel is null) continue;
            var childName = rel.ChildType.Name;
            var propName = rel.Property.Name;
            sb.AppendLine($"    void Attach{propName}({parentName} parent, IEnumerable<{childName}> children);");
        }
        sb.AppendLine("}");

        context.AddSource($"{graphName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string? FindKeyType(INamedTypeSymbol type)
    {
        var idProp = type.GetMembers()
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p => p.Name is "Id" or "ID");

        return idProp?.Type.ToDisplayString();
    }

    private sealed record GraphInfo(
        INamedTypeSymbol ParentType,
        IPropertySymbol Property,
        ITypeSymbol ChildType);
}